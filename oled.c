static void OLED_Config(void) {
    GPIO_InitTypeDef GPIO_InitStructure;
    I2C_InitTypeDef I2C_InitStructure;

    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOB | RCC_APB2Periph_AFIO, ENABLE);
    RCC_APB1PeriphClockCmd(RCC_APB1Periph_I2C1, ENABLE);

    // SDA-PB7, SCL-PB6
    GPIO_InitStructure.GPIO_Pin = GPIO_Pin_6 | GPIO_Pin_7;
    GPIO_InitStructure.GPIO_Mode = GPIO_Mode_AF_OD; 
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_Init(GPIOB, &GPIO_InitStructure);

    I2C_InitStructure.I2C_Mode = I2C_Mode_I2C;
    I2C_InitStructure.I2C_DutyCycle = I2C_DutyCycle_2;
    I2C_InitStructure.I2C_OwnAddress1 = 0x00;
    I2C_InitStructure.I2C_Ack = I2C_Ack_Disable;
    I2C_InitStructure.I2C_AcknowledgedAddress = I2C_AcknowledgedAddress_7bit;
    I2C_InitStructure.I2C_ClockSpeed = 400000;
    I2C_Init(I2C1, &I2C_InitStructure);
    
    I2C_Cmd(I2C1, ENABLE);
}

static void OLED_WriteData(uint8_t data) {
    while(I2C_GetFlagStatus(I2C1, I2C_FLAG_BUSY));
    I2C_GenerateSTART(I2C1, ENABLE);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_MODE_SELECT));

    I2C_Send7bitAddress(I2C1, OLED_I2C_ADDR, I2C_Direction_Transmitter);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_TRANSMITTER_MODE_SELECTED));

    I2C_SendData(I2C1, 0x40); // gui data
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_BYTE_TRANSMITTING));

    I2C_SendData(I2C1, data);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_BYTE_TRANSMITTED));

    I2C_GenerateSTOP(I2C1, ENABLE);
}


static void OLED_WriteCommand(uint8_t command) {
    while(I2C_GetFlagStatus(I2C1, I2C_FLAG_BUSY));
    I2C_GenerateSTART(I2C1, ENABLE);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_MODE_SELECT));

    I2C_Send7bitAddress(I2C1, OLED_I2C_ADDR, I2C_Direction_Transmitter);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_TRANSMITTER_MODE_SELECTED));

    I2C_SendData(I2C1, 0x00); 
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_BYTE_TRANSMITTING));

    I2C_SendData(I2C1, command);
    while(!I2C_CheckEvent(I2C1, I2C_EVENT_MASTER_BYTE_TRANSMITTED));

    I2C_GenerateSTOP(I2C1, ENABLE);
}


void Oled_Init(void){
    OLED_Config();

    OLED_WriteCommand(0xAE); // oled on
    OLED_WriteCommand(0x20); 
    OLED_WriteCommand(0x00);
    
    
    OLED_WriteCommand(0xA1); 
    OLED_WriteCommand(0xC8); 
  

    OLED_WriteCommand(0x8D); 
    OLED_WriteCommand(0x14); 
    OLED_WriteCommand(0xAF);  // oled off

    Oled_Clear();
    Oled_UpdateScreen();
}

void Oled_Draw(uint8_t x, uint8_t y, uint8_t color) {
    if(x >= OLED_WIDTH || y >= OLED_HEIGHT) return;
    
    if(color == OLED_COLOR_WHITE) {
        OLED_BUFFER[x + (y / 8) * OLED_WIDTH] |= (1 << (y % 8));
    } else {
        OLED_BUFFER[x + (y / 8) * OLED_WIDTH] &= ~(1 << (y % 8));
    }
}


void Oled_Clear(void) {
	uint16_t i;
    for(i = 0; i < sizeof(OLED_BUFFER); i++) {
        OLED_BUFFER[i] = 0x00;
    }
}

void Oled_UpdateScreen(void) {
	uint8_t i, j;
    for(i = 0; i < 8; i++) {
        OLED_WriteCommand(0xB0 + i); 
        OLED_WriteCommand(0x00);     
        OLED_WriteCommand(0x10);     
        
        for(j = 0; j < OLED_WIDTH; j++) {
            OLED_WriteData(OLED_BUFFER[i * OLED_WIDTH + j]);
        }
    }
}

void Oled_PrintString(uint8_t x, uint8_t y, char *str, uint8_t color) {
    while (*str) {
        if (x + 6 > OLED_WIDTH) { 
            x = 0;
            y += 8;
        }
        if (y + 8 > OLED_HEIGHT) break;

        Oled_ASCII(x, y, *str, color);
        x += 6;
        str++;
    }
}

void Oled_PrintChar(uint8_t x, uint8_t y, char c, uint8_t color) {
    uint8_t i, j;
    if (c < 32 || c > 126) c = ' '; 

    for (i = 0; i < 5; i++) {
        uint8_t line = Font5x7[c - 32][i];
        for (j = 0; j < 7; j++) {
            if (line & (1 << j)) {
                Oled_Draw(x + i, y + j, color);
            }
        }
    }
}
